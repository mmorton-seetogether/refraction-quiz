"""Convert the refraction MCQ Word document into questions.js for the quiz app.

Usage:
    python tools/docx_to_questions.py "path/to/Refraction final assessment 50 MCQs.docx"

Expected document layout (after the answer sheet):
    Heading 1      -> section name (e.g. "Visual acuity")
    Heading 2      -> question label (e.g. "Q3")
    Normal         -> question stem (one or more paragraphs)
    List Paragraph -> answer options, in order A-D; the correct one ends with "[correct]"

Requires: pip install python-docx
"""
import json
import pathlib
import sys

import docx

MARK = "[correct]"


def parse(path):
    doc = docx.Document(path)
    questions, section, current = [], None, None
    started = False
    for p in doc.paragraphs:
        text = p.text.strip()
        style = p.style.name
        if style == "Title":
            started = True
            continue
        if not started or not text:
            continue
        if style == "Heading 1":
            section = text
        elif style == "Heading 2":
            current = {"id": text, "section": section, "stem": [], "options": [], "answer": None}
            questions.append(current)
        elif current is None:
            continue
        elif style == "List Paragraph":
            if text.endswith(MARK):
                current["answer"] = len(current["options"])
                text = text[: -len(MARK)].rstrip()
            current["options"].append(text)
        else:
            current["stem"].append(text)

    problems = []
    for q in questions:
        if q["answer"] is None:
            problems.append(f"{q['id']}: no option marked {MARK}")
        if len(q["options"]) < 2:
            problems.append(f"{q['id']}: only {len(q['options'])} option(s)")
        if not q["stem"]:
            problems.append(f"{q['id']}: no question text")
    return questions, problems


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    questions, problems = parse(sys.argv[1])
    if problems:
        sys.exit("Problems found, questions.js not written:\n  " + "\n  ".join(problems))
    out = pathlib.Path(__file__).resolve().parent.parent / "questions.js"
    body = json.dumps(questions, ensure_ascii=False, indent=2)
    out.write_text(
        "// Generated by tools/docx_to_questions.py. Edit the Word document and re-run,\n"
        "// or edit this file directly. \"answer\" is the 0-based index of the correct option.\n"
        f"window.QUIZ_TITLE = \"Refraction final assessment\";\nwindow.QUESTIONS = {body};\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(questions)} questions to {out}")


if __name__ == "__main__":
    main()
